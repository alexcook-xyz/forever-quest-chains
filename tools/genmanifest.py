#!/usr/bin/env python3
"""Generated-data guard.

Generated Lua is never hand-edited. A generated file carries a marker line
near its top and is recorded in ``tools/generated.manifest.json`` with the
sha256 of the bytes the generator wrote. ``check`` fails when:

* a file with the marker is missing from the manifest (unregistered output),
* a manifest entry points at a missing file, or
* a file's hash differs from the manifest (hand-edit or stale regeneration).

The fix for any failure is to change the extractor/generator, regenerate,
then run ``update`` to record the new hashes. Never edit the Lua by hand.

Usage:
    python tools/genmanifest.py check
    python tools/genmanifest.py update
"""
from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ADDON_DIR = "MainStoryGuide"
MANIFEST = pathlib.Path(__file__).resolve().parent / "generated.manifest.json"
MARKER = "-- GENERATED by tools/"
MARKER_SCAN_LINES = 5


def file_hash(path: pathlib.Path) -> str:
    """sha256 over the file with line endings normalised to LF."""
    data = path.read_bytes().replace(b"\r\n", b"\n")
    return hashlib.sha256(data).hexdigest()


def is_generated(path: pathlib.Path) -> bool:
    with path.open("r", encoding="utf-8", errors="replace") as fh:
        head = [fh.readline() for _ in range(MARKER_SCAN_LINES)]
    return any(line.startswith(MARKER) for line in head)


def find_generated(root: pathlib.Path = ROOT) -> list[str]:
    """Repo-relative POSIX paths of Lua files that carry the marker."""
    found = []
    for path in sorted((root / ADDON_DIR).rglob("*.lua")):
        if is_generated(path):
            found.append(path.relative_to(root).as_posix())
    return found


def load_manifest(path: pathlib.Path = MANIFEST) -> dict[str, str]:
    if not path.exists():
        return {}
    return json.loads(path.read_text(encoding="utf-8")).get("files", {})


def write_manifest(files: dict[str, str], path: pathlib.Path = MANIFEST) -> None:
    doc = {"version": 1, "files": dict(sorted(files.items()))}
    path.write_text(json.dumps(doc, indent=2) + "\n", encoding="utf-8", newline="\n")


def check(root: pathlib.Path = ROOT, manifest_path: pathlib.Path = MANIFEST) -> list[str]:
    """Return a list of problems; empty means the generated data is clean."""
    manifest = load_manifest(manifest_path)
    problems: list[str] = []
    generated = find_generated(root)
    for rel in generated:
        if rel not in manifest:
            problems.append(f"{rel}: generated file is not in the manifest (run update after regenerating)")
    for rel, expected in manifest.items():
        path = root / rel
        if not path.exists():
            problems.append(f"{rel}: listed in the manifest but missing")
        elif file_hash(path) != expected:
            problems.append(
                f"{rel}: differs from the recorded generator output (hand-edited or stale); "
                "fix the extractor and regenerate, never edit generated Lua"
            )
    return problems


def update(root: pathlib.Path = ROOT, manifest_path: pathlib.Path = MANIFEST) -> dict[str, str]:
    files = {rel: file_hash(root / rel) for rel in find_generated(root)}
    write_manifest(files, manifest_path)
    return files


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("command", choices=["check", "update"])
    args = ap.parse_args(argv)
    if args.command == "update":
        files = update()
        print(f"genmanifest: recorded {len(files)} generated file(s)")
        return 0
    problems = check()
    if problems:
        for p in problems:
            print(f"genmanifest: FAIL {p}", file=sys.stderr)
        return 1
    print(f"genmanifest: OK ({len(load_manifest())} generated file(s) match the manifest)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
