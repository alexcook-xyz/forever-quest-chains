#!/usr/bin/env python3
"""Write Journal_Dungeons.lua, Journal_Reputations.lua and Journal_Raids.lua, Journal_ZGAQ.lua and Journal_Naxx.lua from the coda facts (issues #20, #22, #23, #24).

One page per quest and one epilogue per chain. A page states only the giver, the place and
the hand-in from `tools/sagas/<name>.facts.json`; it never states objective prose, a motive or
an event that the facts do not give. A quest name with a first or second person word gets the
title `The Task of <giver>`, because `tests/test_story_voice.py` scans journal titles.

    python tools/write_coda_journals.py          # write both files
    python tools/write_coda_journals.py --check  # exit 1 when a committed file is out of date
"""
from __future__ import annotations

import json
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import gen_saga as gs  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
SAGAS = ROOT / "tools" / "sagas"
ADDON = ROOT / "MainStoryGuide"
PERSON = re.compile("(?<![A-Za-z])(you|your|yours|me|my|mine|i|we|us|our)(?![A-Za-z])", re.I)
HEAD = """-- GENERATED by tools/write_coda_journals.py from tools/sagas/{stem}.facts.json. Do not edit.
-- MainStoryGuide: {what} journal.
--
-- One page per chain quest and one epilogue per chain. Close third person,
-- world-focused. Each page states only the giver, the place and the hand-in
-- from the Questie/PandaBase facts; it states no objective prose, motive or
-- event that the facts do not give (tests/test_story_voice.py).

local _, ns = ...
ns.JournalEntries = ns.JournalEntries or {{}}
ns.JournalEpilogues = ns.JournalEpilogues or {{}}

local E = {{
"""
KINDS = {
    "dungeons": ("dungeon codas", "Dungeons", lambda c, f: f"The quest belongs to {c['zone']}."),
    "reputations": ("reputation chains", "Reputations", lambda c, f: f"The quest belongs to the {c['name']} reputation."),
    # A raid chain also holds the quests that its raid quests need, and those start in other zones.
    "raids": ("raid quests", "Raids", lambda c, f: f"The quest is a required step of the {c['name']} chain."),
    "zg_aq": ("Zul'Gurub and Ahn'Qiraj", "ZGAQ", lambda c, f: f"The quest is a step of the {c['name']} chain."),
    "naxx": ("Naxxramas and Plaguelands", "Naxx", lambda c, f: f"The quest is a step of the {c['name']} chain."),
}
# The closing line of the endgame spine (issue #24). It states only how the guide is built: the
# chains of the specs `raids`, `zg_aq` and `naxx`. It gives no event or motive.
SPINE_CLOSE = (" This chain closes the endgame spine of the guide, which also holds the Molten Core,"
               " Blackwing Lair, Zul'Gurub and Ahn'Qiraj chains.")


def render(stem: str) -> str:
    what, _, place = KINDS[stem]
    spec = gs.load_spec(SAGAS / f"{stem}.json")  # checks chain ids, which are written as bare Lua keys
    for chain in spec["chains"]:
        for sq in chain["quests"]:
            if type(sq["id"]) is not int:  # quest IDs are bare Lua numbers too
                raise gs.SpecError(f"chain {chain['id']}: quest ID {sq['id']!r} must be an integer")
    facts = json.loads((SAGAS / f"{stem}.facts.json").read_text(encoding="utf-8"))
    quests, pages = gs.facts_index(facts)
    out, epilogues = [HEAD.format(what=what, stem=stem)], []
    for chain in spec["chains"]:
        out.append(f"-- {chain['name']} " + "-" * max(3, 60 - len(chain["name"])) + "\n")
        first = last = None
        for sq in chain["quests"]:
            fact, pb = quests[sq["id"]], pages.get(sq["id"]) or {}
            giver, point = gs._giver(sq, fact, pb)
            giver_zone = point["zone"] if point else gs.endpoint_zone(fact["startedBy"], pb.get("startedBy"))
            same = gs._ends_at_giver(sq, fact, pb)
            turn = giver if same else gs.endpoint_name(fact["finishedBy"], pb.get("finishedBy"))
            turn_zone = None if same else gs.endpoint_zone(fact["finishedBy"], pb.get("finishedBy"))
            where = f" in {giver_zone}" if giver_zone and giver_zone != chain["zone"] else ""
            hand_in = (f"The hand-in went back to {giver}." if same
                       else f"The hand-in went to {turn}{' in ' + turn_zone if turn_zone else ''}.")
            body = f"{giver}{where} gave this task. {place(chain, fact)} {hand_in}"
            title = f"The Task of {giver}" if PERSON.search(fact["name"]) else fact["name"]
            out.append(f"[{sq['id']}] = {{ title = {gs.lua_str(title)},\n  body = {gs.lua_str(body)} }},\n")
            first = first or (fact["name"], giver)
            last = (fact["name"], turn)  # the quest name stays out of the epilogue: it may hold a banned word
        n = len(chain["quests"])
        body = (f"{chain['name']} holds {n} quest{'s' if n != 1 else ''}. In the order of the guide, "
                f"the first quest starts with {first[1]} and the last quest ends with {last[1]}.")
        if chain["id"] == "naxxramas":
            body += SPINE_CLOSE
        epilogues.append(f"{chain['id']} = {{ title = {gs.lua_str('Epilogue: ' + chain['name'])},\n"
                         f"  body = {gs.lua_str(body)} }},\n")
    out.append("}\nfor id, e in pairs(E) do ns.JournalEntries[id] = e end\n\nlocal P = {\n")
    out += epilogues
    out.append("}\nfor id, e in pairs(P) do ns.JournalEpilogues[id] = e end\n")
    return "".join(out)


def main(argv: list[str] | None = None) -> int:
    check = "--check" in (argv if argv is not None else sys.argv[1:])
    stale = []
    for stem, (_, file, _) in KINDS.items():
        path = ADDON / f"Journal_{file}.lua"
        text = render(stem)
        if check:
            if not path.exists() or path.read_bytes().replace(b"\r\n", b"\n") != text.encode("utf-8"):
                stale.append(path.name)
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.name}")
    if stale:
        print(f"out of date: {stale}; run python tools/write_coda_journals.py", file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
