def make_class_chain(classes=("WARRIOR",), route=None):
    """A spec with the main chain c1 and a class chain c2 of two quests (issue #41)."""
    spec, facts = make(route=route)
    spec["chains"].append({"id": "c2", "name": "Class Chain", "zone": "Dun Morogh", "summary": "A sigil waits.",
                           "classSpecific": True, "walkers": ["Dwarf"],
                           "quests": [{"id": 3116}, {"id": 3117}]})
    facts["quests"] += [fact(3116, "Sigil One", STEN, classes=list(classes)),
                        fact(3117, "Sigil Two", STEN, classes=list(classes))]
    return spec, facts


def test_class_chain_is_written_with_its_flag_and_class_rows():
    # issue #41: the Data Lua marks the chain, and each row keeps its `class` field.
    data, route, report = gs.build(*make_class_chain())
    assert "  classSpecific = true,\n" in data
    assert data.count("classSpecific = true") == 1  # the main chain has no flag
    chain = data[data.index('{ id = "c2"'):]
    assert 'class = "WARRIOR"' in chain and chain.count("class =") == 2
    assert "3116" not in route and "3117" not in route  # no class quest on the route
    assert report["classGated"] == [3116, 3117]


def test_class_chain_with_two_classes_lists_both():
    data, _, _ = gs.build(*make_class_chain(classes=("WARRIOR", "PALADIN")))
    assert 'class = "PALADIN, WARRIOR"' in data


