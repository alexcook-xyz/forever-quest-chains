@pytest.mark.parametrize("spec_path", SPECS, ids=lambda p: p.stem)
def test_committed_lua_matches_a_fresh_build(spec_path, tmp_path):
    report = gs.run_build(spec_path, addon=tmp_path, write_report=False)
    spec = json.loads(spec_path.read_text(encoding="utf-8"))
    stem = spec.get("file", report["saga"])
    names = [f"Data_{stem}.lua"] + ([] if spec.get("chainsOnly") else [f"Route_{stem}.lua"])
    for name in names:
        fresh = (tmp_path / name).read_text(encoding="utf-8")
        committed = (ROOT / "MainStoryGuide" / name).read_text(encoding="utf-8").replace("\r\n", "\n")
        assert committed == fresh, f"{name} is stale or hand-edited; run python tools/gen_saga.py build --all"


