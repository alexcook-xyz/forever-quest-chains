def npc(npc_id, name, zone, *points):
    return {"id": npc_id, "name": name, "zoneID": zone, "spawns": {str(zone): [list(p) for p in points]}}


def fact(qid, name, giver, finisher=None, **extra):
    base = {
        "id": qid, "source": "questie", "name": name, "requiredLevel": 1, "questLevel": 3,
        "races": ["Human", "Dwarf", "Night Elf", "Gnome"], "classes": [], "objectivesText": [],
        "startedBy": {"creatures": [giver] if giver else [], "objects": [], "items": []},
        "finishedBy": {"creatures": [finisher or giver] if (finisher or giver) else [], "objects": [], "items": []},
        "preQuestGroup": [], "preQuestSingle": [],
    }
    base.update(extra)
    return base


STEN = npc(658, "Sten Stoutarm", 1, (29.9, 71.2))
TALIN = npc(714, "Talin Keeneye", 1, (22.6, 71.4))
# A PandaBase page whose giver is a located object (no Questie creature).
BARREL_PAGE = {"startedBy": {"name": "Suspicious Barrel", "kind": "object", "zone": "Loch Modan",
                             "x": 47.0, "y": 13.0, "located": True}}


def make(spec_quests=None, route=None, facts_list=None, pages=None, walkers=None):
    spec = {
        "saga": "Dwarf", "_name": "dwarf",
        "chains": [{"id": "c1", "name": "Chain One", "zone": "Dun Morogh", "summary": "Snow lies on the valley.",
                    "walkers": walkers or ["Dwarf"],
                    "quests": spec_quests or [{"id": 179, "task": "Speak with Sten Stoutarm."}, {"id": 233}]}],
        "route": route or [179, 233],
    }
    facts = {"quests": facts_list or [fact(179, "Dwarven Outfitters", STEN),
                                      fact(233, "Coldridge Valley Mail Delivery", STEN, TALIN)],
             "pandabase_pages": {str(k): v for k, v in (pages or {}).items()}}
    return spec, facts


def test_points_come_from_spawns_and_turn_in_goes_to_route():
    data, route, report = gs.build(*make())
    assert data.startswith("-- GENERATED by tools/gen_saga.py")
    assert '{ id = 179, name = "Dwarven Outfitters", giver = "Sten Stoutarm", zone = "Dun Morogh", ' \
           'map = 1426, x = 29.9, y = 71.2, reqlevel = 1 }' in data
    assert 'ns.RegisterRoute("Dwarf", ROUTE)' in route
    assert '[233] = { turn = { name = "Talin Keeneye", zone = "Dun Morogh", map = 1426, x = 22.6, y = 71.4 } },' in route
    assert '[179] = { task = "Speak with Sten Stoutarm." },' in route
    assert report["manual"] == []


