def test_prefetch_fetches_each_id_once_and_keeps_results_by_id():
    import threading

    lock, calls = threading.Lock(), []

    def fetch(qid):
        with lock:
            calls.append(qid)
        return None if qid == 3 else {"id": qid}

    pages = {1: {"id": 1}}                        # already cached
    gs.prefetch([1, 2, 3, 4, 2], fetch, pages, workers=3)
    assert sorted(calls) == [2, 3, 4]
    assert pages == {1: {"id": 1}, 2: {"id": 2}, 3: None, 4: {"id": 4}}
    gs.prefetch([2, 3, 4], fetch, pages)          # a second spec: no new requests
    assert len(calls) == 3


