# ------------------------------------------------------------------ helpers
def npc(npc_id, name, zone, *points):
    return {"id": npc_id, "name": name, "zoneID": zone, "spawns": {str(zone): [list(p) for p in points]}}


def fact(qid, name, giver, **extra):
    base = {
        "id": qid, "source": "questie", "name": name, "requiredLevel": 50, "questLevel": 52,
        "races": [], "classes": [], "objectivesText": [],
        "startedBy": {"creatures": [giver], "objects": [], "items": []},
        "finishedBy": {"creatures": [giver], "objects": [], "items": []},
        "preQuestGroup": [], "preQuestSingle": [],
    }
    base.update(extra)
    return base


