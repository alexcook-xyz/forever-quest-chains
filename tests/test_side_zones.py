def side_spec(*quest_ids, zone="Burning Steppes"):
    return {"sideZones": True, "file": "ZoneSideQuests", "_name": "side_zones",
            "zones": [{"name": zone, "quests": [{"id": i} for i in quest_ids]}]}


def side_facts(*facts_list, pages=None):
    return {"quests": list(facts_list), "pandabase_pages": {str(k): v for k, v in (pages or {}).items()}}


def committed():
    spec = gs.load_side_spec(SPEC_PATH)
    spec["_name"] = "side_zones"
    facts = json.loads((SAGAS / "side_zones.facts.json").read_text(encoding="utf-8"))
    return spec, facts


