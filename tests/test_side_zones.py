# ------------------------------------------------------------ engine (Lua)
CORE_SRC = (ADDON / "Core.lua").read_text(encoding="utf-8")


def core_slice(start: str, end: str) -> str:
    a, b = CORE_SRC.index(start), CORE_SRC.index(end)
    return CORE_SRC[a:b]


def load_engine(faction):
    """ZoneCatalog from the real Core.lua, with the real side file and one MAIN quest."""
    lua = lua51.LuaRuntime(unpack_returned_tuples=True)
    parts = [core_slice("function ns.IsClassSpecificQuest", "function ns.IsChainIncluded"),
             core_slice("function ns.PlayerFaction", "function ns.PlayerClass"),
             core_slice("function ns.QuestEligible", "-- The included quests of a chain"),
             core_slice("function ns.ZoneOf(quest)", "function ns.ZonesForQuests"),
             core_slice("function ns.ZoneCatalog", "-- Spoiler-gated view models")]
    src = "\n".join(parts)
    run = lua.eval(r"""
      function(src, side, faction)
        UnitFactionGroup = faction and function() return faction, faction end or nil
        local ns = {}
        ns.QuestIndex = {}
        ns.StoryRoute = {}
        ns.Chains = {}
        local function EnsureIndex() end
        local chunk = assert(loadstring("local ns, EnsureIndex = ...\n" .. src))
        assert(loadstring(side))(nil, ns)
        chunk(ns, EnsureIndex)
        return ns
      end""")
    side = (ADDON / "ZoneSideQuests.lua").read_text(encoding="utf-8")
    return run(src, side, faction)


def lua_ids(cat_side):
    return [cat_side[i]["id"] for i in range(1, len(cat_side) + 1)]


