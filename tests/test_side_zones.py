    main = gs.main_ids()
    ids = set(gs.side_ids(spec))
    lua = (ADDON / "ZoneSideQuests.lua").read_text(encoding="utf-8")
    for zone in spec["zones"]:
        pos = {q["id"]: n for n, q in enumerate(zone["quests"])}
        for sq in zone["quests"]:
            row = next(ln for ln in lua.splitlines() if f"{{ id = {sq['id']}," in ln)
            m = re.search(r"requires = \{([0-9, ]+)\}", row)
