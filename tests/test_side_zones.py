def test_a_faction_sees_only_its_own_and_neutral_side_rows(spec_and_lua, zone, faction):
    spec, side_of = spec_and_lua
    ns = load_engine(faction)
    shown = set(lua_ids(ns.ZoneCatalog(zone)["side"]))
    listed = [q["id"] for z in spec["zones"] if z["name"] == zone for q in z["quests"]]
